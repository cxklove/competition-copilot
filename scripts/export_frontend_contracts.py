def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    directory = ROOT / "frontend/src/runtime/generated"
    for name, text in artifacts().items():
        path = directory / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise SystemExit(f"Frontend contract drift: regenerate {path.relative_to(ROOT)}")
        else:
            directory.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    fixture = ROOT / "frontend/tests/fixtures/runtime.json"
    text = fixtures()
    if args.check:
        if not fixture.exists() or fixture.read_text(encoding="utf-8") != text:
            raise SystemExit("Frontend fixture drift: regenerate")
    else:
        fixture.parent.mkdir(parents=True, exist_ok=True)
        fixture.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
