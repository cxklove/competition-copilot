def behavioral_cases(values):
    """P12 computes accept/reject and canonical values, never frontend expectations."""
    cases = []

    def case(name, kind, base, path, replacement):
        raw = deepcopy(base)
        target = raw
        for key in path[:-1]:
            target = target[key]
        target[path[-1]] = deepcopy(replacement)
        model = AgentArtsInvocationEnvelope if kind == "input" else PublicRuntimeResult
        try:
            # No invented defaults: compare the fields actually sent on the wire.
            expected = model.model_validate(raw).model_dump(mode="json", exclude_unset=True)
        except ValidationError:
            expected = None
        cases.append({"name": name, "kind": kind, "raw": raw, "expected": expected})

    request = {"request": values["request"]}
    for value in ("request-1", " request-1 ", "   ", "", True, "\u0085request-1\u001f"):
        case(f"request identity {value!r}", "input", request, ["request", "request_id"], value)
    for value in ("valid message", " valid message ", "", "   ", 123, "\ufeff"):
        case(f"response message {value!r}", "output", values["completed"], ["response", "message"], value)
    for value in ([], ["milestone-2", "milestone-1"], ["milestone-1", "milestone-1"],
                  [" milestone-1 ", "milestone-1"], [" milestone-1 "], ["   "]):
        for field in ("before_plan", "proposed_after_plan"):
            base = deepcopy(values["approval"])
            base["response"]["approval_request"][field] = deepcopy(base["response"]["approval_request"]["before_plan"])
            case(f"{field} milestones {value!r}", "output", base,
                 ["response", "approval_request", field, "milestone_ids"], value)
    for value in (" approval-1 ", "   "):
        case(f"approval identity {value!r}", "input", values["approve_reply"],
             ["approval", "approval_request_id"], value)
    case("clarification blank question", "output", values["clarification"],
         ["response", "clarification", "question"], "   ")
    case("clarification duplicate fields", "output", values["clarification"],
         ["response", "clarification", "fields"], ["COMPETITION", "COMPETITION"])
    case("clarification canonical fields", "output", values["clarification"],
         ["response", "clarification", "fields"], ["TRACK", "COMPETITION"])
    case("clarification empty reply", "input", values["clarification_reply"], ["clarification", "values"], {})
    case("clarification normalized target", "input", values["clarification_reply"],
         ["clarification", "values", "competition_id"], " competition-1 ")
