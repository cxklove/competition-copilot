class PublicRuntimeResult(AgentContract):
    """Minimal hosting projection, not another AgentResponse or business result."""

    response: AgentResponse | None = None
    error: RuntimeError | None = None
    continuation_ref: StableId | None = None
    continuation: None = None  # Accept completed P12 wire null; never internal GraphInput.

    @model_validator(mode="after")
    def safe_outcome(self) -> Self:
        if (self.response is None) == (self.error is None):
            raise ValueError("Exactly one response or runtime error")
        pending = self.response is not None and self.response.outcome in (
            "NEEDS_CLARIFICATION", "WAITING_FOR_APPROVAL")
        if pending != (self.continuation_ref is not None):
            raise ValueError("Pending response requires safe continuation_ref")
        return self


MODELS = (AgentRequest, AgentResponse, ClarificationResponse, ApprovalResponse,
          AgentArtsInvocationEnvelope, PublicRuntimeResult)


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(v) for v in schema["anyOf"])
    kind = schema.get("type")
    if kind == "object":
        if isinstance(schema.get("additionalProperties"), dict):
            return f'Record<string, {ts_type(schema["additionalProperties"])}>'
        required = schema.get("required", [])
        fields = [f'{json.dumps(k)}{"" if k in required else "?"}: {ts_type(v)}'
                  for k, v in schema.get("properties", {}).items()]
        return "{ " + "; ".join(fields) + " }"
    if kind == "array":
        return f'Array<{ts_type(schema["items"])}>'
    if kind in ("string", "boolean", "null"):
        return kind
    if kind in ("integer", "number"):
        return "number"
    raise ValueError(f"Unsupported schema for type export: {schema}")


def artifacts():
    schemas = {model.__name__: model.model_json_schema(mode="validation") for model in MODELS}
    definitions = {}
    for schema in schemas.values():
        for name, value in schema.get("$defs", {}).items():
            if name in definitions and definitions[name] != value:
                raise ValueError(f"Conflicting public definition {name}")
            definitions[name] = value
    definitions.update({name: {k: v for k, v in value.items() if k != "$defs"}
                        for name, value in schemas.items()})
    assert not {"AgentState", "GraphInput", "HumanResume"} & definitions.keys()
    types = "// Generated by scripts/export_frontend_contracts.py; do not edit.\n"
    types += "\n".join(f"export type {name} = {ts_type(value)};"
                       for name, value in sorted(definitions.items())) + "\n"
    # StringConstraints.strip_whitespace is not represented by JSON Schema.
    # Derive consumer normalization hints from public Pydantic field annotations.
    rules = {}

    def rule(annotation, utc=False):
        args = get_args(annotation)
        if get_origin(annotation) is Annotated:
            if any(isinstance(v, StringConstraints) and v.strip_whitespace for v in args[1:]):
                return "strip"
            return rule(args[0], utc)
        if annotation in (datetime, AwareDatetime) and utc:
            return "utc"
        if isinstance(annotation, type) and issubclass(annotation, BaseModel):
            collect(annotation)
        if get_origin(annotation) in (list, tuple):
            item = rule(args[0], utc)
            return {"items": item} if item else None
        for arg in args:
            item = rule(arg, utc)
            if item:
                return item
        return None

    def collect(model):
        if model.__name__ in rules:
            return
        rules[model.__name__] = {}
        for name, field in model.model_fields.items():
            value = rule(field.rebuild_annotation(), issubclass(model, AgentContract))
            if value:
                rules[model.__name__][name] = value

    for model in MODELS:
        collect(model)
    schemas["normalization"] = rules
    return {"contracts.json": json.dumps(schemas, indent=2, sort_keys=True) + "\n",
            "contracts.ts": types}


