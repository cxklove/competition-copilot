    case("reply UTC normalization", "input", values["approve_reply"],
         ["approval", "submitted_at"], "2026-10-19T08:00:00.123456+08:00")
    case("context parent required", "input", request, ["request", "context"], {"edition_id": "edition-1"})
    case("context wrong profile kind", "input", request, ["request", "context"],
         {"profile_ref": {"kind": "SOURCE", "ref_id": "profile-1"}})
