MODELS = (CompetitionDetailProjection, EligibilityDecision, RecommendationEvaluation, SkillGapDecision,
          PlanDiff, Evidence, SourceMetadata, CompetitionPlan, RecommendationRankingResult,
          ListCompetitionsOutput, GetCompetitionOutput)
MODEL_BY_NAME = {model.__name__: model for model in MODELS}


def artifacts():
    export = runpy.run_path(str(ROOT / "scripts/export_frontend_contracts.py"))
    schemas = {model.__name__: model.model_json_schema() for model in MODELS}
    definitions = {}
    for schema in schemas.values():
        for key, value in schema.get("$defs", {}).items():
            if key in definitions and definitions[key] != value:
                raise ValueError(f"Conflicting artifact definition: {key}")
            definitions[key] = value
    definitions.update({key: {k: v for k, v in schema.items() if k != "$defs"}
                        for key, schema in schemas.items()})
    types = "// Generated by scripts/export_frontend_results.py; do not edit.\n"
    def union_schema(value):
        if isinstance(value, dict):
            return {("anyOf" if key == "oneOf" else key): union_schema(item)
                    for key, item in value.items()}
        if isinstance(value, list):
            return [union_schema(item) for item in value]
        return value

    types += "\n".join(f"export type {key} = {export['ts_type'](union_schema(value))};"
                       for key, value in sorted(definitions.items())) + "\n"
    return {"artifacts.json": json.dumps(schemas, indent=2, sort_keys=True) + "\n",
            "artifacts.ts": types}


def fixtures():
    # Existing supplied-contract test factories, not frontend business calculations.
    replanning = runpy.run_path(str(ROOT / "backend/tests/domain/test_replanning_contract.py"))
    gaps = runpy.run_path(str(ROOT / "backend/tests/domain/test_skill_gap.py"))
    source = SourceMetadata(source_url="https://example.org/synthetic-rules",
                            source_type="manual", observed_at="2030-01-01T00:00:00Z",
                            verification_status="verified")
    evidence = Evidence(code="SYNTHETIC_RULE", message="Synthetic reviewed rule, not a real competition fact.",
                        source=source, field="education", value="undergraduate")
    cases = {}

    def case(name, model, value, kind, *, message="预设结果；仅演示展示，不代表真实业务判断。", plans=()):
        value = MODEL_BY_NAME[model].model_validate(value)
        ref = {"kind": kind, "ref_id": f"presentation-{name}"}
        reasons = getattr(value, "reason_codes", ())
        if isinstance(value, PlanDiff):
            reasons = value.decision.reason_codes
        intent = {"EligibilityDecision": "CHECK_ELIGIBILITY", "SkillGapDecision": "ANALYZE_SKILL_GAP",
                  "RecommendationEvaluation": "GET_RECOMMENDATIONS",
                  "PlanDiff": "EXPLAIN_REPLANNING"}.get(model, "UNKNOWN")
        response = AgentResponse(request_id="request-1", intent=intent, outcome="COMPLETED",
                                 message=message, plan_refs=plans,
                                 audit={"results": [ref], "reasons": [
                                     {"result": ref, "reason_code": reason} for reason in reasons]})
        cases[name] = {"runtime": {"response": response.model_dump(mode="json", exclude_none=True)},
                       "bundle": {"request_id": "request-1", "artifacts": [
                           {"ref": ref, "model": model, "value": value.model_dump(mode="json")}]}}

    for status, reason in (("eligible", "RULE_SATISFIED"), ("ineligible", "RULE_VIOLATED"),
                           ("unknown", "PROFILE_DATA_MISSING")):
        rule = {"rule_id": "synthetic-rule", "scope": "competition", "target_id": "competition",
                "status": status, "reason_code": reason, "message": evidence.message,
                "evidence": [evidence]}
        value = EligibilityDecision(status=status, competition_id="competition", edition_id="edition",
                                    reason_codes=[reason], evidence=[evidence], rule_evaluations=[rule])
        case(status, "EligibilityDecision", value, "ELIGIBILITY_RESULT")
    for name, coverage, status, items in (
        ("undetermined", "MISSING", "UNDETERMINED", ()),
        ("no_gap", "COMPLETE", "NO_GAP", (gaps["item"](),)),
    ):
        value = gaps["decision"](gaps["SkillRequirementCoverage"][coverage],
                                 gaps["SkillGapStatus"][status], items)
        case(name, "SkillGapDecision", value, "SKILL_GAP_RESULT")
    recommendations = runpy.run_path(str(ROOT / "backend/tests/domain/test_recommendation.py"))
    recommended = recommendations["evaluation"](
        recommendations["EligibilityStatus"].ELIGIBLE,
        recommendations["RecommendationStatus"].RECOMMENDED,
        recommendations["RecommendationReasonCode"].SUITABILITY_ASSESSED,
        score=0.8, components=[recommendations["component"](0.8)],
    )
    case("recommendation", "RecommendationEvaluation", recommended, "RECOMMENDATION_RESULT")
    case("verified_source", "SourceMetadata", source, "SOURCE")
    before = replanning["plan"](milestones=(
        replanning["PlanMilestone"](id="m1", title="保留并更新的任务"),
        replanning["PlanMilestone"](id="removed", title="被移除的任务"),
    ))
    impact = replanning["impact"]("affects_plan", source=replanning["event"](field="track_membership"), current=before)
    decision = replanning["decision"]("replan", impacts=(impact,))
    after = replanning["revised"](before, (
        replanning["PlanMilestone"](id="m1", title="更新后的任务"),
        replanning["PlanMilestone"](id="added", title="新增的任务"),
    ))
    diff = PlanDiff(before=before, after=after, decision=decision, evaluated_at=replanning["T3"],
                    changes=(PlanMilestonesChange(before=before.milestones, after=after.milestones),))
    case("plan_diff", "PlanDiff", diff, "PLAN_DIFF",
         plans=(PlanReference.from_plan(before), PlanReference.from_plan(after)))
    keep = replanning["decision"]("keep_current_plan", impacts=(replanning["impact"]("no_plan_impact", current=before),))
    noop = PlanDiff(before=before, after=before, decision=keep, evaluated_at=replanning["T3"])
    case("no_change", "PlanDiff", noop, "PLAN_DIFF", message="预设拒绝后回复：返回的方案未改变。",
         plans=(PlanReference.from_plan(before),))
    pending_source = SourceMetadata.model_validate({**source.model_dump(), "verification_status": "pending"})
    for name, value in (("pending_source", evidence.model_copy(update={"source": pending_source})),
                        ("partial_evidence", Evidence(code="PARTIAL_SYNTHETIC", message="只有依据文本，未提供来源。"))):
        case(name, "Evidence", value.model_dump(mode="json"), "EVIDENCE")
    return json.dumps(cases, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = {ROOT / "frontend/src/results/generated" / name: value for name, value in artifacts().items()}
    files[ROOT / "frontend/src/demo/result-fixtures.json"] = fixtures()
    for path, value in files.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != value:
                raise SystemExit(f"Result projection drift: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
